export const FONTS = { big: { glyphs: F5, h: 7, gap: 1 }, small: { glyphs: F3, h: 5, gap: 1 } };

// Returns list of filled pixels {x, y} with y=0 at the BOTTOM of the text, plus total width/height.
export function layoutText(str, fontName = 'big') {
  const font = FONTS[fontName];
  const pixels = [];
  let x = 0;
  const up = String(str).normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/[’‘“”–…×№]/g, (c) => FOLD[c]).toUpperCase();
  for (let ci = 0; ci < up.length; ci++) {
    const ch = up[ci];
    const g = font.glyphs[ch] || font.glyphs['?'];
    let x0 = 0, w = g[0].length;
    if (fontName === 'big' && NARROW[ch]) { x0 = NARROW[ch][0]; w = NARROW[ch][1]; }
    for (let r = 0; r < font.h; r++) {
      const row = g[r] || '';
      for (let c = x0; c < x0 + w; c++) if (row[c] === '#') pixels.push({ x: x + c - x0, y: font.h - 1 - r });
    }
    x += w + font.gap;
  }
  return { pixels, width: Math.max(0, x - font.gap), height: font.h };
}
